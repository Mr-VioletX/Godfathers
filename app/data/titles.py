import json as _json

TITLES_BY_NAME = {t["name"]: t for t in TITLES}


def get_title_by_name(name: str) -> Optional[dict]:
    """یافتنِ لقب بر اساسِ نامِ نمایشیِ فارسی (برای سیستمِ قدیمِ پروفایل)."""
    if not name:
        return None
    return TITLES_BY_NAME.get(name.strip())


def load_titles(raw: Optional[str]) -> list:
    """رشته‌ی JSONِ Player.earned_titles را به لیستِ نامِ القاب تبدیل می‌کند.
    اگر خالی/نامعتبر باشد، لیستِ خالی برمی‌گرداند (ضدِ کرش)."""
    if not raw:
        return []
    try:
        data = _json.loads(raw)
    except (ValueError, TypeError):
        return []
    if isinstance(data, list):
        return [str(x) for x in data]
    return []


def dump_titles(titles: list) -> str:
    """لیستِ نامِ القاب را برای ذخیره در Player.earned_titles به JSON تبدیل می‌کند."""
    return _json.dumps(list(dict.fromkeys(titles or [])), ensure_ascii=False)


