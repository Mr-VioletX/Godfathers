def progression_for(level: int) -> dict:
    """نزدیک‌ترین بلوکِ راهنما برای سطحِ فعلی را برمی‌گرداند."""
    chosen = PROGRESSION[0]
    for block in PROGRESSION:
        if level >= block["min_level"]:
            chosen = block
        else:
            break
    return chosen


def clean_name(raw: str) -> str | None:
    """نامِ ورودی را تمیز و اعتبارسنجی می‌کند؛ None یعنی نامعتبر."""
    name = (raw or "").strip()
    if not name or len(name) > MAX_NAME_LEN:
        return None
    return name
