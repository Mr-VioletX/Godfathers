def _clamp_level(level: int) -> int:
    try:
        level = int(level)
    except (TypeError, ValueError):
        level = 1
    if level < 1:
        return 1
    if level > ASSISTANT_MAX_LEVEL:
        return ASSISTANT_MAX_LEVEL
    return level


def upgrade_info(level: int) -> dict:
    """اطلاعاتِ سطحِ فعلی."""
    return UPGRADES[_clamp_level(level)]


def next_upgrade(level: int) -> dict | None:
    """بلوکِ سطحِ بعدی یا None اگر به سقف رسیده باشد."""
    level = _clamp_level(level)
    if level >= ASSISTANT_MAX_LEVEL:
        return None
    return UPGRADES[level + 1]


def unlocked_features(level: int) -> list:
    """فهرستِ تجمعیِ بخش‌هایِ بازشده تا این سطح (به ترتیب)."""
    level = _clamp_level(level)
    feats: list = []
    for lvl in range(1, level + 1):
        for key in UPGRADES[lvl]["unlocks"]:
            if key not in feats:
                feats.append(key)
    return feats


def can_report(level: int, feature: str) -> bool:
    """آیا دستیار در این سطح مجاز به گزارشِ این بخش است؟"""
    return feature in unlocked_features(level)


def feature_label(key: str) -> str:
    return FEATURES.get(key, key)


def upgrade_cost(target_level: int) -> int:
    """هزینه‌ی رسیدن به سطحِ هدف."""
    return UPGRADES[_clamp_level(target_level)]["cost"]


